class _GenerationControls extends StatelessWidget {
  const _GenerationControls({
    required this.phase,
    required this.routing,
    required this.failure,
    required this.failureMessage,
    required this.isStale,
    required this.canGenerate,
    required this.onGenerate,
    required this.onCancel,
    required this.onRetry,
    required this.onEditText,
  });
  final _Phase phase;
  final RoutingDecided? routing;
  final Failure? failure;
  final String failureMessage;
  final bool isStale;
  final bool canGenerate;
  final VoidCallback onGenerate;
  final VoidCallback onCancel;
  final VoidCallback onRetry;
  final VoidCallback onEditText;

  @override
  Widget build(BuildContext context) {
    switch (phase) {
      case _Phase.generating:
        final onDevice = routing?.onDevice ?? true;
        final reason = routing?.reason;
        return Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          Row(children: [
            const Expanded(
              child: LinearProgressIndicator(minHeight: 6, color: Hs.blue500, backgroundColor: Hs.cloud200),
            ),
            const SizedBox(width: 10),
            HsButton('Cancel', variant: HsVariant.cancel, height: 32, onTap: onCancel),
          ]),
          const SizedBox(height: 8),
          Text(
            onDevice ? 'On-device · erasing existing text' : 'Cloud · this may take a little longer',
            style: const TextStyle(fontSize: 12, color: Hs.textSecondary),
          ),
          if (!onDevice && reason != null) ...[
            const SizedBox(height: 4),
            Text(reason, style: const TextStyle(fontSize: 12, color: Hs.textTertiary)),
          ],
        ]);

      case _Phase.success:
        if (isStale) {
          // Task 7.3: text changed since this artwork was generated -- the
          // Specifications edge case (nothing auto-regenerates on edit).
          // Falls back to the same idle-style "Generate" row rather than
          // "Regenerate", since the existing artwork no longer reflects
          // what's in the text field.
          return Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
            Row(children: [
              const Icon(Icons.info_outline, size: 16, color: Hs.amber500),
              const SizedBox(width: 6),
              const Expanded(
                child: Text('Artwork may be outdated — text has changed since generation',
                    style: TextStyle(fontSize: 12, color: Hs.textSecondary)),
              ),
            ]),
            const SizedBox(height: 8),
            HsButton('Generate artwork with AI', onTap: canGenerate ? onGenerate : null),
          ]);
        }
        return Row(children: [
          HsButton('Regenerate', variant: HsVariant.secondary, onTap: canGenerate ? onGenerate : null),
          const SizedBox(width: 10),
          const Text('Generated just now', style: TextStyle(fontSize: 12, color: Hs.textSecondary)),
        ]);

      case _Phase.failure:
        return Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          Row(children: [
            const Icon(Icons.error_outline, size: 16, color: Hs.coral500),
            const SizedBox(width: 6),
            Expanded(
                child: Text(failureMessage,
                    style: const TextStyle(fontSize: 13, color: Hs.textBody))),
          ]),
          const SizedBox(height: 10),
          Row(children: [
            HsButton('Retry', onTap: failure!.retryable ? onRetry : null),
            const SizedBox(width: 10),
            HsButton('Edit text', variant: HsVariant.secondary, onTap: onEditText),
          ]),
        ]);

      case _Phase.idle:
        return Row(children: [
          HsButton('Generate artwork with AI', onTap: canGenerate ? onGenerate : null),
          const SizedBox(width: 10),
          const Text('(o) On-device', style: TextStyle(fontSize: 12, color: Hs.textSecondary)),
        ]);
    }
  }
}
