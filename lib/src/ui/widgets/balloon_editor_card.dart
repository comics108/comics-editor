    required this.isFilled,
    required this.hasText,
    required this.onTap,
  });
  final String code;
  final bool isSelected;
  final bool isFilled; // has artwork -- filled tab per 02-visual.md
  final bool hasText;
  final VoidCallback onTap;

  @override
  Widget build(BuildContext context) {
    return InkWell(
      onTap: onTap,
      borderRadius: BorderRadius.circular(Hs.rChip),
      child: Container(
        height: 32,
        padding: const EdgeInsets.symmetric(horizontal: 10),
        alignment: Alignment.center,
        decoration: BoxDecoration(
          color: isFilled ? Hs.blue500 : (isSelected ? Hs.blue100 : Hs.white),
          border: Border.all(color: isFilled ? Hs.blue500 : Hs.cloud200),
